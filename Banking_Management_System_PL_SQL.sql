-- -------------------------
-- 5. PACKAGE BODY
-- Procedures do not COMMIT. The calling program controls COMMIT/ROLLBACK.
-- -------------------------
CREATE OR REPLACE PACKAGE BODY bank_pkg AS

    PROCEDURE add_customer(
        p_full_name IN VARCHAR2,
        p_email     IN VARCHAR2,
        p_phone     IN VARCHAR2,
        p_address   IN VARCHAR2,
        p_customer_id OUT NUMBER
    ) IS
    BEGIN
        IF TRIM(p_full_name) IS NULL OR TRIM(p_email) IS NULL OR TRIM(p_phone) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20001, 'Name, email and phone are required.');
        END IF;

        INSERT INTO customers(full_name, email, phone, address)
        VALUES (TRIM(p_full_name), LOWER(TRIM(p_email)), TRIM(p_phone), p_address)
        RETURNING customer_id INTO p_customer_id;
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20002, 'A customer with this email already exists.');
    END add_customer;


    PROCEDURE open_account(
        p_customer_id IN NUMBER,
        p_account_type IN VARCHAR2,
        p_initial_deposit IN NUMBER,
        p_account_id OUT NUMBER
    ) IS
        v_customer_count NUMBER;
    BEGIN
        SAVEPOINT sp_open_account;

        IF p_initial_deposit IS NULL OR p_initial_deposit < 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Initial deposit cannot be negative.');
        END IF;

        IF UPPER(p_account_type) NOT IN ('SAVINGS','CURRENT') THEN
            RAISE_APPLICATION_ERROR(-20004, 'Account type must be SAVINGS or CURRENT.');
        END IF;

        SELECT COUNT(*) INTO v_customer_count
        FROM customers WHERE customer_id = p_customer_id;

        IF v_customer_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Customer does not exist.');
        END IF;

        INSERT INTO accounts(customer_id, account_type, balance)
        VALUES (p_customer_id, UPPER(p_account_type), p_initial_deposit)
        RETURNING account_id INTO p_account_id;

        IF p_initial_deposit > 0 THEN
            INSERT INTO bank_transactions(account_id, transaction_type, amount, description)
            VALUES (p_account_id, 'DEPOSIT', p_initial_deposit, 'Initial account deposit');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO sp_open_account;
            RAISE;
    END open_account;


    PROCEDURE deposit(
        p_account_id IN NUMBER,
        p_amount IN NUMBER,
        p_description IN VARCHAR2 DEFAULT 'Cash deposit'
    ) IS
        v_status accounts.account_status%TYPE;
    BEGIN
        SAVEPOINT sp_deposit;

        IF p_amount IS NULL OR p_amount <= 0 THEN
            RAISE_APPLICATION_ERROR(-20006, 'Deposit amount must be greater than zero.');
        END IF;

        SELECT account_status INTO v_status
        FROM accounts
        WHERE account_id = p_account_id
        FOR UPDATE;

        IF v_status <> 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20007, 'Only active accounts can transact.');
        END IF;

        UPDATE accounts SET balance = balance + p_amount
        WHERE account_id = p_account_id;

        INSERT INTO bank_transactions(account_id, transaction_type, amount, description)
        VALUES (p_account_id, 'DEPOSIT', p_amount, p_description);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK TO sp_deposit;
            RAISE_APPLICATION_ERROR(-20008, 'Account not found.');
        WHEN OTHERS THEN
            ROLLBACK TO sp_deposit;
            RAISE;
    END deposit;


    PROCEDURE withdraw(
        p_account_id IN NUMBER,
        p_amount IN NUMBER,
        p_description IN VARCHAR2 DEFAULT 'Cash withdrawal'
    ) IS
        v_balance accounts.balance%TYPE;
        v_status accounts.account_status%TYPE;
    BEGIN
        SAVEPOINT sp_withdraw;

        IF p_amount IS NULL OR p_amount <= 0 THEN
            RAISE_APPLICATION_ERROR(-20009, 'Withdrawal amount must be greater than zero.');
        END IF;

        SELECT balance, account_status INTO v_balance, v_status
        FROM accounts
        WHERE account_id = p_account_id
        FOR UPDATE;

        IF v_status <> 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20012, 'Only active accounts can transact.');
        END IF;

        IF v_balance < p_amount THEN
            RAISE_APPLICATION_ERROR(-20013, 'Insufficient balance.');
        END IF;

        UPDATE accounts SET balance = balance - p_amount
        WHERE account_id = p_account_id;

        INSERT INTO bank_transactions(account_id, transaction_type, amount, description)
        VALUES (p_account_id, 'WITHDRAWAL', p_amount, p_description);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK TO sp_withdraw;
            RAISE_APPLICATION_ERROR(-20014, 'Account not found.');
        WHEN OTHERS THEN
            ROLLBACK TO sp_withdraw;
            RAISE;
    END withdraw;


    PROCEDURE transfer(
        p_from_account IN NUMBER,
        p_to_account IN NUMBER,
        p_amount IN NUMBER,
        p_description IN VARCHAR2 DEFAULT 'Fund transfer'
    ) IS
        v_from_balance accounts.balance%TYPE;
        v_from_status accounts.account_status%TYPE;
        v_to_balance accounts.balance%TYPE;
        v_to_status accounts.account_status%TYPE;
        v_reference VARCHAR2(40);
    BEGIN
        SAVEPOINT sp_transfer;

        IF p_from_account = p_to_account THEN
            RAISE_APPLICATION_ERROR(-20015, 'Source and destination accounts must be different.');
        END IF;

        IF p_amount IS NULL OR p_amount <= 0 THEN
            RAISE_APPLICATION_ERROR(-20016, 'Transfer amount must be greater than zero.');
        END IF;

        -- Lock rows in ascending account_id order to reduce deadlock risk.
        IF p_from_account < p_to_account THEN
            SELECT balance, account_status INTO v_from_balance, v_from_status
            FROM accounts WHERE account_id = p_from_account FOR UPDATE;

            SELECT balance, account_status INTO v_to_balance, v_to_status
            FROM accounts WHERE account_id = p_to_account FOR UPDATE;
        ELSE
            SELECT balance, account_status INTO v_to_balance, v_to_status
            FROM accounts WHERE account_id = p_to_account FOR UPDATE;

            SELECT balance, account_status INTO v_from_balance, v_from_status
            FROM accounts WHERE account_id = p_from_account FOR UPDATE;
        END IF;

        IF v_from_status <> 'ACTIVE' OR v_to_status <> 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20017, 'Both accounts must be active.');
        END IF;

        IF v_from_balance < p_amount THEN
            RAISE_APPLICATION_ERROR(-20018, 'Insufficient balance for transfer.');
        END IF;

        v_reference := 'TRF-' || TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF3');

        UPDATE accounts SET balance = balance - p_amount
        WHERE account_id = p_from_account;

        UPDATE accounts SET balance = balance + p_amount
        WHERE account_id = p_to_account;

        INSERT INTO bank_transactions(account_id, transaction_type, amount, description, reference_no)
        VALUES (p_from_account, 'TRANSFER_OUT', p_amount, p_description, v_reference);

        INSERT INTO bank_transactions(account_id, transaction_type, amount, description, reference_no)
        VALUES (p_to_account, 'TRANSFER_IN', p_amount, p_description, v_reference);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK TO sp_transfer;
            RAISE_APPLICATION_ERROR(-20019, 'Source or destination account not found.');
        WHEN OTHERS THEN
            ROLLBACK TO sp_transfer;
            RAISE;
    END transfer;


    FUNCTION get_balance(p_account_id IN NUMBER) RETURN NUMBER IS
        v_balance NUMBER(14,2);
    BEGIN
        SELECT balance INTO v_balance
        FROM accounts
        WHERE account_id = p_account_id;
        RETURN v_balance;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20020, 'Account not found.');
    END get_balance;


    PROCEDURE print_statement(
        p_account_id IN NUMBER,
        p_from_date IN DATE DEFAULT TRUNC(SYSDATE) - 30,
        p_to_date IN DATE DEFAULT TRUNC(SYSDATE) + 1
    ) IS
        CURSOR c_statement IS
            SELECT transaction_id, transaction_type, amount,
                   transaction_date, description, reference_no
            FROM bank_transactions
            WHERE account_id = p_account_id
              AND transaction_date >= p_from_date
              AND transaction_date < p_to_date + 1
            ORDER BY transaction_date, transaction_id;
        v_found BOOLEAN := FALSE;
    BEGIN
        DBMS_OUTPUT.PUT_LINE('--- ACCOUNT STATEMENT: ' || p_account_id || ' ---');
        FOR rec IN c_statement LOOP
            v_found := TRUE;
            DBMS_OUTPUT.PUT_LINE(
                rec.transaction_id || ' | ' ||
                RPAD(rec.transaction_type, 12) || ' | ' ||
                TO_CHAR(rec.amount, 'FM9999999990.00') || ' | ' ||
                TO_CHAR(rec.transaction_date, 'DD-MON-YYYY HH24:MI') || ' | ' ||
                NVL(rec.description, '-') || ' | ' || NVL(rec.reference_no, '-')
            );
        END LOOP;

        IF NOT v_found THEN
            DBMS_OUTPUT.PUT_LINE('No transactions found for the selected period.');
        END IF;

        DBMS_OUTPUT.PUT_LINE('Current balance: ' ||
            TO_CHAR(get_balance(p_account_id), 'FM9999999990.00'));
    END print_statement;

END bank_pkg;
