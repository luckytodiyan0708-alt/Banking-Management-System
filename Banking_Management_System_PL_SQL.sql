-- -------------------------
-- 2. TABLE CREATION
-- -------------------------
CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR2(100) NOT NULL,
    email         VARCHAR2(120) NOT NULL UNIQUE,
    phone         VARCHAR2(15)  NOT NULL,
    address       VARCHAR2(250),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE accounts (
    account_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER NOT NULL,
    account_type  VARCHAR2(10) NOT NULL,
    balance       NUMBER(14,2) DEFAULT 0 NOT NULL,
    account_status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    opened_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id),
    CONSTRAINT chk_account_type CHECK (account_type IN ('SAVINGS','CURRENT')),
    CONSTRAINT chk_account_balance CHECK (balance >= 0),
    CONSTRAINT chk_account_status CHECK (account_status IN ('ACTIVE','BLOCKED','CLOSED'))
);

CREATE TABLE bank_transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     NUMBER NOT NULL,
    transaction_type VARCHAR2(20) NOT NULL,
    amount         NUMBER(14,2) NOT NULL,
    transaction_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    description    VARCHAR2(250),
    reference_no   VARCHAR2(40),
    CONSTRAINT fk_txn_account FOREIGN KEY (account_id)
        REFERENCES accounts(account_id),
    CONSTRAINT chk_txn_type CHECK (
        transaction_type IN ('DEPOSIT','WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT')
    ),
    CONSTRAINT chk_txn_amount CHECK (amount > 0)
);

CREATE INDEX idx_accounts_customer ON accounts(customer_id);
CREATE INDEX idx_txn_account_date ON bank_transactions(account_id, transaction_date);

-- -------------------------
-- 3. TRIGGER
-- Validates transaction data before insertion.
-- -------------------------
CREATE OR REPLACE TRIGGER trg_validate_bank_txn
BEFORE INSERT ON bank_transactions
FOR EACH ROW
BEGIN
    IF :NEW.amount IS NULL OR :NEW.amount <= 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'Transaction amount must be greater than zero.');
    END IF;

    IF :NEW.transaction_type NOT IN
       ('DEPOSIT','WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT') THEN
        RAISE_APPLICATION_ERROR(-20011, 'Invalid transaction type.');
    END IF;
END;
