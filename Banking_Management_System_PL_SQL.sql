-- View all customers and their accounts:
SELECT c.customer_id, c.full_name, c.email,
       a.account_id, a.account_type, a.balance, a.account_status
FROM customers c
LEFT JOIN accounts a ON a.customer_id = c.customer_id
ORDER BY c.customer_id, a.account_id;

-- View all transactions:
SELECT transaction_id, account_id, transaction_type, amount,
       transaction_date, description, reference_no
FROM bank_transactions
ORDER BY transaction_id;

-- Total deposits and withdrawals by account:
SELECT account_id,
       SUM(CASE WHEN transaction_type IN ('DEPOSIT','TRANSFER_IN') THEN amount ELSE 0 END) AS total_credits,
       SUM(CASE WHEN transaction_type IN ('WITHDRAWAL','TRANSFER_OUT') THEN amount ELSE 0 END) AS total_debits
FROM bank_transactions
GROUP BY account_id
ORDER BY account_id;

-- Customer-wise total account balance:
SELECT c.customer_id, c.full_name, SUM(a.balance) AS total_balance
FROM customers c
JOIN accounts a ON a.customer_id = c.customer_id
GROUP BY c.customer_id, c.full_name
ORDER BY total_balance DESC;

